
import org.jdbi.v3.core.Jdbi;

import java.util.ArrayList;
import java.util.Collections;

public class Database {

    // java database interface
    private Jdbi jdbi;


    /*
     database constructor
       connects to the database and creates the database and tables if they dont exist
     */
    public Database() {
        connect();
        createTables();
    }

    /*
    connects to the database, if it does not exist it creates it
     */
    public void connect() {
        jdbi = Jdbi.create(
                "jdbc:hsqldb:file:./data/dbDogPension",
                "",
                ""
        );
    }

    /*
    creates the tables if they dont exist
     */
    public void createTables() {

        jdbi.useHandle(handle -> {

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblFoodType (
                    fldFoodTypeID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldFoodTypeName VARCHAR(50)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblDog (
                    fldDogID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldDogName VARCHAR(50),
                    fldDogAge TINYINT,
                    fldDogBreed VARCHAR(50),
                    fldDogSpecialNeeds VARCHAR(1000),
                    fldDogPrefferedVet TINYINT,
                    fldDogWeight TINYINT,
                    fldDogPensionDuration TINYINT,
                    fldIsDogVaccinated BOOLEAN,
                    fldIsDogTreatedForFleas BOOLEAN,
                    fldIsDogInsured BOOLEAN,
                    fldDogFoodTypeID INTEGER,
                    fldOwnerID INTEGER,

                    FOREIGN KEY (fldDogFoodTypeID)
                        REFERENCES tblFoodType(fldFoodTypeID)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblOwner (
                    fldOwnerID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldOwnerName VARCHAR(50),
                    fldOwnerPhoneNo VARCHAR(20)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblFeeding (
                    fldFeedingDateTime TIMESTAMP,
                    tblFeedingID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldDogID INTEGER,
                    fldFoodTypeID INTEGER,

                    FOREIGN KEY (fldDogID)
                        REFERENCES tblDog(fldDogID),

                    FOREIGN KEY (fldFoodTypeID)
                        REFERENCES tblFoodType(fldFoodTypeID)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblIncident (
                    fldIncidentID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldDogID INTEGER NOT NULL,
                    fldIncidentLog VARCHAR(1000),

                    FOREIGN KEY (fldDogID)
                        REFERENCES tblDog(fldDogID)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblVetVisit (
                    fldDogID INTEGER NOT NULL,
                    fldVetID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldReason VARCHAR(50),
                    fldDateTime TIMESTAMP,

                    FOREIGN KEY (fldDogID)
                        REFERENCES tblDog(fldDogID)
                )
            """);

            handle.execute("""
                CREATE TABLE IF NOT EXISTS tblWalk (
                    fldWalkID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fldDistance DOUBLE,
                    fldDateTime TIMESTAMP,
                    fldDogID INTEGER,

                    FOREIGN KEY (fldDogID)
                        REFERENCES tblDog(fldDogID)
                )
            """);

        });
    }

    /*
    method to get the data from a specific table and column
    takes the table and column as strings and returns an arrarlist<object> of the data
     */
    public ArrayList<Object> getData(String table, String column) {
        return jdbi.withHandle(handle ->
                new ArrayList<>(
                        handle.createQuery("SELECT " + column + " FROM " + table)
                                .map((rs, ctx) -> rs.getObject(1))
                                .list()
                )
        );
    }

    /*
    method to get the data from a specific table and column, where a specific condition applies
    takes the table, column and whereColumn as strings, and the specific value as object and returns an arrarlist<object> of the data
     */
    public ArrayList<Object> getDataWhereDataIs(String table, String column, Object value, String whereColumn) {

        return jdbi.withHandle(handle ->
                new ArrayList<>(
                        handle.createQuery("SELECT " + column + " FROM " + table + " WHERE " + whereColumn + " = :value")
                                .bind("value", value)
                                .map((rs, ctx) -> rs.getObject(1))
                                .list()
                )
        );
    }

    /*
    inserting data into a given table
    takes tableName, a string arraylist of the columns and a object arraylist of the data
    return nothing
     */
    public void insertData(String tableName, ArrayList<String> columns, ArrayList<Object> data) {
        String sql = "INSERT INTO " + tableName + " (" + String.join(",", columns) + ") VALUES ("
                + String.join(",", Collections.nCopies(data.size(), "?")) + ")";

        jdbi.useHandle(handle -> handle.execute(sql, data.toArray()));
    }

    /*
    method only used for wiping database during testing
    deleted all data in all databases
     */
    public void wipeDatabaseData() {
        jdbi.useHandle(handle -> {
            handle.execute("DELETE FROM tblFeeding");
            handle.execute("DELETE FROM tblIncident");
            handle.execute("DELETE FROM tblVetVisit");
            handle.execute("DELETE FROM tblWalk");
            handle.execute("DELETE FROM tblOwner");
            handle.execute("DELETE FROM tblDog");
            handle.execute("DELETE FROM tblFoodType");
        });
    }
}
